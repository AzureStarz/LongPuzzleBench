function a(id: string, x: number, y: number, occupied: boolean): AnchorData {
    return { id, x, y, occupied };
}

function b(
    id: string, x: number, y: number, rotDeg: number, texIdx: number,
    cw: number, ch: number, holes: { x: number; y: number }[],
    order: number, linDamp: number, angDamp: number, attached: string[]
): BoardData {
    return {
        id, x, y, rotationDegrees: rotDeg, textureIndex: texIdx,
        collisionWidth: cw, collisionHeight: ch, holeOffsets: holes,
        renderOrder: order, linearDamp: linDamp, angularDamp: angDamp,
        attachedAnchors: attached,
    };
}

function p(id: string, attachedAnchor: string, x: number, y: number, radius: number = 70, order: number = 5): AnchorPadData {
    return { id, x, y, radius, renderOrder: order, attachedAnchors: [attachedAnchor] };
}

function cp(
    id: string, x: number, y: number, radius: number,
    order: number, attached: string[], holes: { x: number; y: number }[]
): AnchorPadData {
    return { id, x, y, radius, renderOrder: order, attachedAnchors: attached, holeOffsets: holes };
}

function holeAt(
    boardX: number, boardY: number, rotDeg: number,
    anchorX: number, anchorY: number
): { x: number; y: number } {
    const rad = rotDeg * Math.PI / 180;
    const cos = Math.cos(rad);
    const sin = Math.sin(rad);
    const dx = anchorX - boardX;
    const dy = anchorY - boardY;
    const round1 = (v: number) => Math.round(v * 10) / 10;
    return {
        x: round1(dx * cos + dy * sin),
        y: round1(dx * sin - dy * cos),
    };
}

function holes(
    boardX: number, boardY: number, rotDeg: number,
    anchors: [number, number][]
): { x: number; y: number }[] {
    return anchors.map(([x, y]) => holeAt(boardX, boardY, rotDeg, x, y));
}

